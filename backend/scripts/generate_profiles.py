"""Generate the SYNTHETIC candidate dataset used by the recommendation API.

Every profile produced here is fictional. No real people, names, photos,
phone numbers or matrimonial data are used. Profiles are identified only by
synthetic IDs (U001, U101, U102, ...).

The generator is deterministic (fixed random seed), so re-running it always
produces exactly the same file and the tests stay reproducible.

Usage (from the repository root):
    python backend/scripts/generate_profiles.py
"""

from __future__ import annotations

import json
import random
from pathlib import Path

SEED = 457  # IT457 :-)
NUM_CANDIDATES = 60

CITIES = [
    "Ahmedabad",
    "Mumbai",
    "Pune",
    "Bengaluru",
    "Delhi",
    "Surat",
    "Vadodara",
    "Hyderabad",
    "Jaipur",
    "Chennai",
]
EDUCATION = ["Engineering", "Medicine", "Science", "Commerce", "Management", "Arts", "Law"]
INTERESTS = [
    "music",
    "travel",
    "technology",
    "reading",
    "cooking",
    "fitness",
    "movies",
    "photography",
    "dance",
    "cricket",
    "art",
    "yoga",
    "gaming",
    "volunteering",
    "hiking",
]

OUTPUT = Path(__file__).resolve().parents[1] / "src" / "data" / "sample_profiles.json"


def build_profiles() -> list[dict]:
    rng = random.Random(SEED)
    profiles: list[dict] = []

    # U001 is the demo "requesting user". It is deliberately present in the
    # dataset so we can prove that the API never recommends a user to themself.
    profiles.append(
        {
            "candidate_id": "U001",
            "age": 25,
            "city": "Ahmedabad",
            "education": "Engineering",
            "interests": ["music", "travel", "technology"],
        }
    )

    # Ahmedabad gets extra weight so the classroom demo has plenty of matches.
    city_weights = [4, 2, 2, 2, 2, 1, 1, 1, 1, 1]
    for i in range(NUM_CANDIDATES):
        profiles.append(
            {
                "candidate_id": f"U{101 + i}",
                "age": rng.randint(21, 38),
                "city": rng.choices(CITIES, weights=city_weights, k=1)[0],
                "education": rng.choice(EDUCATION),
                "interests": sorted(rng.sample(INTERESTS, k=rng.randint(2, 5))),
            }
        )

    # Three hand-curated (still fictional) profiles so the classroom demo shows
    # what strong, medium and partial matches look like for the U001 example.
    profiles.extend(
        [
            {
                "candidate_id": "U161",
                "age": 26,
                "city": "Ahmedabad",
                "education": "Engineering",
                "interests": ["music", "technology", "travel"],
            },
            {
                "candidate_id": "U162",
                "age": 24,
                "city": "Ahmedabad",
                "education": "Science",
                "interests": ["music", "photography", "travel"],
            },
            {
                "candidate_id": "U163",
                "age": 27,
                "city": "Vadodara",
                "education": "Engineering",
                "interests": ["reading", "technology"],
            },
        ]
    )
    return profiles


def main() -> None:
    document = {
        "dataset": "synthetic-matchmaking-profiles",
        "version": "1.0",
        "synthetic": True,
        "notice": "Fictional profiles generated by backend/scripts/generate_profiles.py. Not real people.",
        "seed": SEED,
        "profiles": build_profiles(),
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(document['profiles'])} synthetic profiles to {OUTPUT}")


if __name__ == "__main__":
    main()
